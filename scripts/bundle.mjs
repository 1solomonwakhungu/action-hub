// Bundles the compiled CLI (and everything it imports, including the in-process
// MCP server) into a single CommonJS file that Node's Single Executable
// Application (SEA) tooling can embed. Run `npm run build` first so the
// workspace `dist/` outputs this bundle pulls from exist.
import { build } from "esbuild";
import { mkdir, rm, writeFile, access } from "node:fs/promises";
import { resolve } from "node:path";
import { repoRoot, readCliVersion } from "./lib/util.mjs";

const entry = resolve(repoRoot, "packages/cli/dist/index.js");
const outDir = resolve(repoRoot, "build");
const outFile = resolve(outDir, "action-hub.cjs");

async function main() {
  try {
    await access(entry);
  } catch {
    throw new Error(
      `Missing ${entry}. Run \`npm run build\` before bundling the standalone binary.`,
    );
  }

  const version = await readCliVersion();
  await rm(outDir, { recursive: true, force: true });
  await mkdir(outDir, { recursive: true });

  // Bundle-time inline of the third-party license/provenance texts (review-1
  // round 5 HIGH 1): the CJS bundle has no filesystem vendor tree next to it,
  // so `action-hub licenses` reads these inlined texts when neither the SEA
  // assets nor a resolvable @action-hub/core vendor dir is available.
  const vendorRoot = resolve(repoRoot, "packages", "core", "vendor");
  const { readFile } = await import("node:fs/promises");
  const embeddedLicenses = {
    "vendor/VENDOR.md": await readFile(resolve(vendorRoot, "VENDOR.md"), "utf8"),
    "vendor/licenses/Apache-2.0.txt": await readFile(resolve(vendorRoot, "licenses/Apache-2.0.txt"), "utf8"),
    "vendor/licenses/onnxruntime-LICENSE.txt": await readFile(resolve(vendorRoot, "licenses/onnxruntime-LICENSE.txt"), "utf8"),
  };
  const embeddedLicensesPlugin = {
    name: "embedded-licenses",
    setup(build) {
      build.onResolve({ filter: /^virtual:embedded-licenses$/ }, () => ({
        path: "virtual:embedded-licenses",
        namespace: "embedded-licenses",
      }));
      build.onLoad({ filter: /.*/, namespace: "embedded-licenses" }, () => ({
        contents: `export const embeddedLicenses = ${JSON.stringify(embeddedLicenses)};`,
        loader: "js",
      }));
    },
  };

  const result = await build({
    entryPoints: [entry],
    bundle: true,
    platform: "node",
    format: "cjs",
    target: "node20",
    outfile: outFile,
    // The single-file executable has no package.json beside it; inline the
    // version so a manifest read is never attempted at runtime.
    define: { "process.env.ACTION_HUB_VERSION": JSON.stringify(version) },
    banner: {
      js: "// Action Hub standalone bundle — generated by scripts/bundle.mjs. Do not edit.",
    },
    legalComments: "none",
    logLevel: "info",
    metafile: true,
    plugins: [embeddedLicensesPlugin],
  });

  const bytes = Object.values(result.metafile.outputs).reduce((sum, o) => sum + o.bytes, 0);
  await writeFile(resolve(outDir, "bundle-meta.json"), JSON.stringify(result.metafile));
  process.stderr.write(
    `Bundled ${entry} -> ${outFile} (${(bytes / 1024 / 1024).toFixed(2)} MiB) for v${version}\n`,
  );
}

main().catch((err) => {
  process.stderr.write(`bundle failed: ${err instanceof Error ? err.stack : String(err)}\n`);
  process.exit(1);
});
