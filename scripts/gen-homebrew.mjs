// Generates a Homebrew formula that installs the prebuilt Action Hub binary for
// the host's OS/arch from a GitHub release. Reads SHA256SUMS.txt so the pinned
// checksums always match the published artifacts.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import {
  repoRoot,
  repoSlug,
  releaseBaseUrl,
  parseChecksums,
  readCliVersion,
} from "./lib/util.mjs";

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--version" && argv[i + 1]) args.version = argv[++i];
    else if (argv[i] === "--checksums" && argv[i + 1]) args.checksums = resolve(argv[++i]);
    else if (argv[i] === "--out" && argv[i + 1]) args.out = resolve(argv[++i]);
  }
  return args;
}

function require256(map, name) {
  const hash = map[name];
  if (!hash) throw new Error(`SHA256SUMS is missing an entry for "${name}"`);
  return hash;
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const version = args.version ?? (await readCliVersion());
  const checksumsPath = args.checksums ?? resolve(repoRoot, "dist-bin", "SHA256SUMS.txt");
  const out = args.out ?? resolve(repoRoot, "packaging", "homebrew", "action-hub.rb");
  const repo = repoSlug();
  const base = releaseBaseUrl(version, repo);

  const map = parseChecksums(await readFile(checksumsPath, "utf8"));
  const macArm = require256(map, "action-hub-macos-arm64");
  const macX64 = require256(map, "action-hub-macos-x64");
  const linArm = require256(map, "action-hub-linux-arm64");
  const linX64 = require256(map, "action-hub-linux-x64");

  const formula = `# Generated by scripts/gen-homebrew.mjs for v${version}. Do not edit by hand.
class ActionHub < Formula
  desc "Indexed, on-demand capability layer for MCP servers and skills"
  homepage "https://github.com/${repo}"
  version "${version}"
  license "MIT"

  on_macos do
    if Hardware::CPU.arm?
      url "${base}/action-hub-macos-arm64"
      sha256 "${macArm}"
    else
      url "${base}/action-hub-macos-x64"
      sha256 "${macX64}"
    end
  end

  on_linux do
    if Hardware::CPU.arm?
      url "${base}/action-hub-linux-arm64"
      sha256 "${linArm}"
    else
      url "${base}/action-hub-linux-x64"
      sha256 "${linX64}"
    end
  end

  def install
    bin.install Dir["action-hub-*"].first => "action-hub"
  end

  test do
    assert_match "action-hub #{version}", shell_output("#{bin}/action-hub --version")
  end
end
`;

  await mkdir(resolve(out, ".."), { recursive: true });
  await writeFile(out, formula);
  process.stderr.write(`Wrote ${out} (v${version})\n`);
}

main().catch((err) => {
  process.stderr.write(`gen-homebrew failed: ${err instanceof Error ? err.stack : String(err)}\n`);
  process.exit(1);
});
