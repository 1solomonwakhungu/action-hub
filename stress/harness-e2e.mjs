/** Promise-based async runner so concurrent harness runs truly overlap.
 *  stdin is "ignore": pi hangs forever when its stdin is an open empty pipe
 *  (found empirically; pi waits for stdin input in -p mode).
 *  The child runs detached in its own process group so the whole tree
 *  (harness + its spawned hub + fake servers) can be torn down reliably. */
function runAsync(cmd, args, env, opts = {}) {
  return new Promise((done) => {
    const child = spawn(cmd, args, { env, cwd: opts.cwd ?? REPO, stdio: ["ignore", "pipe", "pipe"], detached: true });
    let stdout = "";
    let stderr = "";
    let settled = false;
    const killTreeChild = (signal) => killTree(child.pid, signal);
    let timedOut = false;
    const timer = setTimeout(() => { timedOut = true; killTree(child.pid, "SIGKILL"); }, opts.timeout ?? TIMEOUT_MS);
    child.stdout.on("data", (d) => (stdout += d));
    child.stderr.on("data", (d) => (stderr += d));
    child.on("error", (cause) => {
      // spawn/ENOENT etc: settle so the last-line JSON is always emitted.
      clearTimeout(timer);
      if (!settled) {
        settled = true;
        stderr += `\nspawn error: ${cause?.message ?? String(cause)}`;
        done({ status: null, stdout, stderr, timedOut, spawnError: cause?.code ?? String(cause) });
      }
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      if (!settled) {
        settled = true;
        killTreeChild("SIGKILL"); // reap any grandchildren the harness left behind
        void (async () => {
          if (child.pid !== undefined) await waitGone(child.pid, 3000);
          done({ status: code, stdout, stderr, timedOut });
        })();
      }
    });
  });
}

