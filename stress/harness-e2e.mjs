async function measureSearchSize(env, query, cli) {
  const t0 = Date.now();
  const r = await runAsync("node", [cli, "test-search", query, "--json", "--limit", "10"], env, { timeout: 120000 });
  return { bytes: r.stdout.length, wallMs: Date.now() - t0, ok: r.status === 0, error: r.status !== 0 ? r.stderr.slice(-300) : undefined };
}

function evaluateHarness(name, result, needle) {
  const out = `${result.stdout}\n${result.stderr}`;
  const foundId = out.includes(needle.id);
  const marker = needle.kind === "skill" ? SKILL_MARKER : TOOL_MARKER;
  // Some harnesses (codex exec) print the final answer on stderr, so marker
  // detection runs over combined output; the latest matching line wins.
  const markerLines = out.split("\n").filter((l) => l.includes(marker));
  const markerLine = markerLines[markerLines.length - 1];
  let tokenOk = false;
  if (markerLine) {
    tokenOk = needle.kind === "tool" ? markerLine.includes(needle.token) : markerLine.includes(needle.passphrase);
  }
  return {
    harness: name,
    exitCode: result.status,
    timedOut: Boolean(result.timedOut),
    foundNeedleId: foundId,
    markerPrinted: Boolean(markerLine),
    // Success = clean exit AND the harness proved it reached the needle:
    // marker printed with the verifiable secret (passphrase for skills, token
    // for tools). A killed/timeout/nonzero run is a failure even if it happened
    // to print the marker first.
    success: result.status === 0 && !result.timedOut && Boolean(markerLine) && tokenOk,
    turns: null, // turn counts are harness-specific; parsed opportunistically below
    wallMs: result.wallMs,
    outputChars: result.stdout.length,
    outputTail: out.slice(-400),
    error: result.status !== 0 ? (result.stderr || result.stdout || "").slice(-400) : undefined,
  };
}

/** Direct JSON-RPC handshake + needle tool execution against the generated
 *  mini server (clean-generation proof). Resolves { ok, error?, token? }. */
function needleServerHandshake(env, needleManifestPath) {
  return new Promise((done) => {
    const child = spawn("node", [join(GEN, "mini-fake-server.mjs"), "--manifest", needleManifestPath], {
      env, stdio: ["pipe", "pipe", "pipe"],
    });
    let out = "";
    let err = "";
    let settled = false;
    const finish = (result) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      try { child.kill("SIGKILL"); } catch { /* gone */ }
      done(result);
    };
    const timer = setTimeout(() => finish({ ok: false, error: "handshake timeout; out=" + out.slice(-200) + " err=" + err.slice(-200) }), 15000);
    child.stdout.on("data", (d) => {
      out += d;
      for (const line of out.split("\n")) {
        if (!line.trim()) continue;
        let msg; try { msg = JSON.parse(line); } catch { continue; }
        if (msg.id === 1) {
          child.stdin.write(JSON.stringify({ jsonrpc: "2.0", method: "notifications/initialized" }) + "\n");
          child.stdin.write(JSON.stringify({ jsonrpc: "2.0", id: 2, method: "tools/call", params: { name: NEEDLE_TOOL_NAME, arguments: { query: "lattice" } } }) + "\n");
        } else if (msg.id === 2) {
          const text = msg.result?.content?.[0]?.text ?? "";
          const ok = !msg.result?.isError && text.includes(NEEDLE_TOOL_TOKEN);
          finish(ok ? { ok: true, token: NEEDLE_TOOL_TOKEN } : { ok: false, error: "needle token missing in result: " + text.slice(-200) });
        }
      }
    });
    child.stderr.on("data", (d) => (err += d));
    child.on("error", (cause) => finish({ ok: false, error: "spawn error: " + cause?.message }));
    child.stdin.write(JSON.stringify({ jsonrpc: "2.0", id: 1, method: "initialize", params: { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "harness-e2e", version: "1.0.0" } } }) + "\n");
  });
}

/** Cross-platform process-tree kill: POSIX group kill, Windows taskkill /T. */
function killTree(pid, signal = "SIGTERM") {
  if (pid === undefined || pid === null || pid <= 0) return;
  if (process.platform === "win32") {
    spawn("taskkill", ["/T", "/F", "/PID", String(pid)], { stdio: "ignore" });
    return;
  }
  try { process.kill(-pid, signal); } catch { /* already gone */ }
  try { process.kill(pid, signal); } catch { /* already gone */ }
}

/** Poll until the pid is gone (bounded) instead of fixed sleeps. */
async function waitGone(pid, timeoutMs) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    if (!stillAlive(pid)) return true;
    await new Promise((r) => setTimeout(r, 100));
  }
  return !stillAlive(pid);
}

function stillAlive(pid) {
  try { process.kill(pid, 0); return true; } catch { return false; }
}

