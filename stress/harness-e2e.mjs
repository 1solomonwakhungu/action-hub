    // fixtures actually serve and to measure the cold-indexed search.
    const coldProbe = await measureSearchSize(env, NEEDLE_SKILL_QUERY, cli);
    summary.fixtures.probeOk = coldProbe.ok;
    summary.searchOutputBytes = coldProbe.bytes;
    if (!coldProbe.ok) summary.errors.push(`probe failed: ${coldProbe.error}`);

