function slugify(text) {
  return text.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

/** Promise-based async runner so concurrent harness runs truly overlap.
 *  stdin is "ignore": pi hangs forever when its stdin is an open empty pipe
 *  (found empirically; pi waits for stdin input in -p mode).
 *  The child runs detached in its own process group so the whole tree
 *  (harness + its spawned hub + fake servers) can be torn down reliably. */
function runAsync(cmd, args, env, opts = {}) {
  return new Promise((done) => {
    const child = spawn(cmd, args, { env, cwd: opts.cwd ?? REPO, stdio: ["ignore", "pipe", "pipe"], detached: true });
    let stdout = "";
    let stderr = "";
    let settled = false;
    const killTree = (signal) => {
      if (child.pid === undefined) return;
      try { process.kill(-child.pid, signal); } catch { /* already gone */ }
      try { child.kill(signal); } catch { /* already gone */ }
    };
    const timer = setTimeout(() => killTree("SIGKILL"), opts.timeout ?? TIMEOUT_MS);
    child.stdout.on("data", (d) => (stdout += d));
    child.stderr.on("data", (d) => (stderr += d));
    child.on("close", (code) => {
      clearTimeout(timer);
      if (!settled) {
        settled = true;
        killTree("SIGKILL"); // reap any grandchildren the harness left behind
        setTimeout(() => done({ status: code, stdout, stderr, timedOut: code === null }), 250);
      }
    });
  });
}

function runSync(cmd, args, env, opts = {}) {
  return spawnSync(cmd, args, { env, encoding: "utf8", timeout: opts.timeout ?? TIMEOUT_MS, cwd: opts.cwd ?? REPO });
}

