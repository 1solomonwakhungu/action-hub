  // codex strips the parent env for MCP server spawns, so the stress config is
  // passed through the TOML env table; startup/tool timeouts are raised above
  // the hub's cold-start window (P1 finding: ~20 s at 15K actions).
  const entryCmd = env["ACTION_HUB_DAEMON_MODE"] ? "connect" : "start";
  const toml = [
    "[mcp_servers.action-hub]",
    `command = "node"`,
    `args = [ "${env["ACTION_HUB_CLI_ENTRY"]}", "${entryCmd}" ]`,
    "startup_timeout_ms = 180000",
    "tool_timeout_ms = 120000",
    "",
    "[mcp_servers.action-hub.env]",
    `ACTION_HUB_CONFIG = "${env["ACTION_HUB_CONFIG"]}"`,
    `ACTION_HUB_SKILLS_DIR = "${env["ACTION_HUB_SKILLS_DIR"]}"`,
    `XDG_CACHE_HOME = "${env["XDG_CACHE_HOME"]}"`,
    ...(env["ACTION_HUB_DAEMON_MODE"] ? [`ACTION_HUB_DAEMON_DIR = "${env["ACTION_HUB_DAEMON_DIR"]}"`] : []),
    "",
  ].join("\n");
  // codex 0.154 reads $CODEX_HOME when set and $HOME/.codex otherwise; write
  // both so the config lands regardless of which one this build honors.
  const codexDirs = [...new Set([env["CODEX_HOME"], join(env["HOME"], ".codex")].filter(Boolean))];
