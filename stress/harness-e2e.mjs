    summary.fleet = {
      servers: tempConfig.servers.length,
      tools: toolCount,
      skills: skillCount,
      fullScale: tempConfig.servers.length >= 45 && toolCount >= 10001 && skillCount >= 5001,
    };
    if (String(summary.fixtures.source).startsWith("builders") && !summary.fleet.fullScale) {
      summary.errors.push(`fleet validation failed: expected 45 servers / 10,001 tools / 5,001 skills, got ${tempConfig.servers.length}/${toolCount}/${skillCount}`);
    }
    summary.fixtures.tempConfigServers = tempConfig.servers.length;

