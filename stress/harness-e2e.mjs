async function measureSearchSize(env, query, cli) {
  const r = await runAsync("node", [cli, "test-search", query, "--json", "--limit", "10"], env, { timeout: 120000 });
  return { bytes: r.stdout.length, ok: r.status === 0, error: r.status !== 0 ? r.stderr.slice(-300) : undefined };
}

function evaluateHarness(name, result, needle) {
  const out = `${result.stdout}\n${result.stderr}`;
  const foundId = out.includes(needle.id);
  const marker = needle.kind === "skill" ? SKILL_MARKER : TOOL_MARKER;
  // Some harnesses (codex exec) print the final answer on stderr, so marker
  // detection runs over combined output; the latest matching line wins.
  const markerLines = out.split("\n").filter((l) => l.includes(marker));
  const markerLine = markerLines[markerLines.length - 1];
  let tokenOk = false;
  if (markerLine) {
    tokenOk = needle.kind === "tool" ? markerLine.includes(needle.token) : markerLine.includes(needle.passphrase);
  }
  return {
    harness: name,
    exitCode: result.status,
    timedOut: Boolean(result.timedOut),
    foundNeedleId: foundId,
    markerPrinted: Boolean(markerLine),
    // Success = the harness proved it reached the needle: marker printed with
    // the verifiable secret (passphrase for skills, token for tools). The id
    // may only appear in intermediate turns, which -p/one-shot modes omit.
    success: Boolean(markerLine) && tokenOk,
    turns: null, // turn counts are harness-specific; parsed opportunistically below
    wallMs: result.wallMs,
    outputChars: result.stdout.length,
    outputTail: out.slice(-400),
    error: result.status !== 0 ? (result.stderr || result.stdout || "").slice(-400) : undefined,
  };
}

// ------------------------------------------------------------------- main

async function main() {
  const started = Date.now();
  const summary = {
    script: "harness-e2e",
    mode: MODE,
    ok: false,
    fixtures: {},
    harnesses: [],
    concurrency: null,
    searchOutputBytes: null,
    errors: [],
  };
  let daemonChild = null;

  try {
    const builderFixtureReady =
      existsSync(join(STRESS, "gen-skills.mjs")) &&
      existsSync(join(STRESS, "gen-tools.mjs")) &&
      existsSync(join(STRESS, "fake-mcp-server.mjs")) &&
      existsSync(join(STRESS, "make-config.mjs"));
    if (!existsSync(join(GEN, "servers.json"))) {
      summary.fixtures = {
        source: builderFixtureReady ? "builders-scripts" : "harness-e2e-fallback",
        generatedAt: new Date().toISOString(),
        fillerSkills: FILLER_SKILLS,
        fillerToolsPerServer: FILLER_TOOLS_PER_SERVER,
      };
      generateFixtures();
    } else {
      summary.fixtures = { source: builderFixtureReady ? "builders-output" : "preexisting" };
    }
    mkdirSync(RESULTS, { recursive: true });

    // Needle fixtures + temp-only config (the generated servers.json is never
    // modified in place; bogus entries like make-config's tools-queries.json
    // artifact are filtered in the temp copy).
    ensureMiniServer();
    const needleManifestPath = ensureNeedleFixtures();
    const generatedServerCount = JSON.parse(readFileSync(join(GEN, "servers.json"), "utf8")).servers?.length ?? 0;

    const cli = cliEntryPath();
    const { root, home, env, dirs } = makeTempRoot();
    env["ACTION_HUB_CONFIG"] = buildTempServersConfig(env, needleManifestPath);
    env["ACTION_HUB_CLI_ENTRY"] = cli;
    if (MODE === "daemon") env["ACTION_HUB_DAEMON_MODE"] = "1";
    summary.fixtures.generatedServers = generatedServerCount;
    summary.fixtures.tempConfigServers = JSON.parse(readFileSync(env["ACTION_HUB_CONFIG"], "utf8")).servers.length;
    summary.tempRoot = KEEP ? root : "(removed)";

    // Hub load check: search to verify the fixtures actually serve.
    const probe = await measureSearchSize(env, NEEDLE_SKILL_QUERY, cli);
    summary.fixtures.probeOk = probe.ok;
    summary.searchOutputBytes = probe.bytes;
    if (!probe.ok) summary.errors.push(`probe failed: ${probe.error}`);

    // Warm the shared catalog cache once (all harness hub instances share the
    // temp HOME cache); report whether warm-up worked.
    summary.cacheWarm = await preWarmCache(env, cli);

    // Optional shared daemon (mode=daemon): up to 3 harnesses against one daemon.
    if (MODE === "daemon") {
      // daemon start's built-in readiness wait is 15 s (START_TIMEOUT_MS in
      // daemon.ts) but cold indexing at 15K actions can take ~20 s+, so poll
      // for the state file well past the CLI's own give-up.
      daemonChild = spawn("node", [cli, "daemon", "start"], { env, stdio: ["ignore", "pipe", "pipe"] });
      daemonChild.unref();
      for (let i = 0; i < 300; i++) {
        await new Promise((r) => setTimeout(r, 500));
        if (existsSync(join(env["ACTION_HUB_DAEMON_DIR"], "daemon.json"))) break;
      }
      summary.daemonStarted = existsSync(join(env["ACTION_HUB_DAEMON_DIR"], "daemon.json"));
    }

    // Install per harness
    const installs = {};
    for (const h of HARNESS_LIST) {
      const def = RUNNERS[h];
      if (!def) continue;
      const inst = installHarness(HARNESS_TARGETS[h] ?? h, env, cli);
      installs[h] = inst.status === 0;
      if (!installs[h]) summary.errors.push(`${h} install failed: ${(inst.stderr || "").slice(-300)}`);
      if (daemonRunningCheck(summary)) {
        if (def.configPath(env).endsWith(".json")) {
          const rewired = useDaemonSnippet(def.configPath(env), cli);
          if (!rewired) summary.errors.push(`${h}: daemon snippet rewiring found no start arg`);
        } else if (h === "codex") {
          summary.codexDaemonToml = true; // runCodex writes connect-mode TOML directly
        } else {
          summary.errors.push(`${h}: daemon mode rewiring unsupported for this config format`);
        }
      }
    }
    summary.installs = installs;

    if (HARNESS_LIST.includes("pi") && installs["pi"]) {
      const piSetupResult = piSetup(env, root);
      if (!piSetupResult.ok) {
        summary.errors.push(`pi setup: ${piSetupResult.note}`);
        installs["pi"] = false;
        summary.installs = installs;
      }
    }

    const needles = {
      skill: { id: `skill:${NEEDLE_SLUG}`, kind: "skill", passphrase: NEEDLE_SKILL_PASSPHRASE },
      tool: { id: `${NEEDLE_TOOL_SERVER}:${NEEDLE_TOOL_NAME}`, kind: "tool", token: NEEDLE_TOOL_TOKEN },
    };

    const runOne = async (h) => {
      const def = RUNNERS[h];
      const t0 = Date.now();
      const result = await def.run(env, def.prompt(), TIMEOUT_MS);
      result.wallMs = Date.now() - t0;
      return evaluateHarness(h, result, needles[def.needleKind]);
    };

    // Sequential runs
    const results = [];
    for (const h of HARNESS_LIST) {
      if (!installs[h]) continue;
      try {
        results.push(await runOne(h));
      } catch (cause) {
        summary.errors.push(`${h} run threw: ${cause?.message ?? String(cause)}`);
      }
    }
    summary.harnesses = results;

    // Concurrency: 3 harnesses at once against the shared daemon
    if (MODE === "daemon") {
      const concurrent = HARNESS_LIST.filter((h) => installs[h]).slice(0, 3);
      const t0 = Date.now();
      const outcomes = await Promise.all(concurrent.map((h) => runOne(h).catch((cause) => ({ harness: h, success: false, error: String(cause) }))));
      summary.concurrency = { harnesses: concurrent, wallMs: Date.now() - t0, results: outcomes };
    }

    if (daemonChild) {
      await runAsync("node", [cli, "daemon", "stop"], env, { timeout: 60000 });
      try { daemonChild.kill("SIGKILL"); } catch { /* already gone */ }
    }

    summary.wallMs = Date.now() - started;
    if (!KEEP) rmSync(root, { recursive: true, force: true });
  } catch (cause) {
    summary.errors.push(`fatal: ${cause?.stack ?? String(cause)}`);
  } finally {
    if (daemonChild) { try { daemonChild.kill("SIGKILL"); } catch { /* gone */ } }
  }

  summary.ok = summary.errors.length === 0 &&
    (summary.harnesses?.length ?? 0) > 0 &&
    summary.harnesses.every((h) => h.success) &&
    (summary.concurrency ? summary.concurrency.results.every((h) => h.success) : true);
  writeFileSync(join(RESULTS, "harness-e2e.json"), JSON.stringify(summary, null, 2), "utf8");
  console.log(JSON.stringify(summary));
  if (!summary.ok) process.exitCode = 1;
}

function daemonRunningCheck(summary) {
  return MODE === "daemon" && summary.daemonStarted === true;
}

await main();