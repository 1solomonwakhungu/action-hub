    // actually runs and returns the token (S6-R3 #2).
    summary.fixtures.needleHandshake = await needleServerHandshake(env, needleManifestPath);
    if (!summary.fixtures.needleHandshake.ok) {
      summary.errors.push(`needle server handshake failed: ${summary.fixtures.needleHandshake.error}`);
    }
    const generatedServerCount = JSON.parse(readFileSync(join(GEN, "servers.json"), "utf8")).servers?.length ?? 0;

