/** Rewires installed snippets from `<cli> start` to `<cli> connect` (daemon mode). */
function useDaemonSnippet(configPath, cli) {
  if (!existsSync(configPath)) return false;
  const doc = JSON.parse(readFileSync(configPath, "utf8"));
  const servers = doc["mcpServers"] ?? doc["mcp"] ?? doc["servers"];
  let changed = false;
  const rewireArray = (arr) => {
    for (let i = 0; i < arr.length; i++) {
      if (arr[i] === "start" && typeof arr[i - 1] === "string" && arr[i - 1].endsWith("index.js")) {
        arr[i] = "connect";
        changed = true;
      }
    }
  };
  for (const entry of Object.values(servers ?? {})) {
    if (Array.isArray(entry?.["command"])) {
      // opencode style: single command array [node, cli, start]
      rewireArray(entry["command"]);
    } else if (Array.isArray(entry?.["args"])) {
      rewireArray(entry["args"]);
    }
  }
  if (changed) writeFileSync(configPath, JSON.stringify(doc, null, 2), "utf8");
  return changed;
}

/** Warm the hub catalog cache in the temp HOME so harness cold starts are fast.
 *  createHubRuntime writes the cache on every boot; a short-lived `start` run
 *  is enough. Without this, hub cold start (~20 s at 15K actions) exceeds
 *  harness MCP init timeouts (codex default ~10 s, pi adapter 30 s). */
async function preWarmCache(env, cli) {
  const child = spawn("node", [cli, "start"], { env, stdio: ["ignore", "pipe", "pipe"] });
  const cachePath = join(env["XDG_CACHE_HOME"] ?? join(env["HOME"], ".cache"), "action-hub", "catalog.json");
  for (let i = 0; i < 120; i++) {
    await new Promise((r) => setTimeout(r, 500));
    if (existsSync(cachePath)) break;
  }
  child.kill("SIGKILL");
  return existsSync(cachePath);
}

