function makeTempRoot() {
  const tmpBase = process.env["TMPDIR"] ?? "/tmp";
  const root = join(tmpBase, `ah-harness-e2e-${process.pid}-${Date.now()}`);
  const home = join(root, "home");
  const dirs = {
    HOME: home,
    USERPROFILE: home,
    APPDATA: join(root, "appdata", "roaming"),
    LOCALAPPDATA: join(root, "appdata", "local"),
    XDG_CACHE_HOME: join(home, ".cache"),
    XDG_CONFIG_HOME: join(home, ".config"),
    XDG_STATE_HOME: join(home, "state"),
    XDG_DATA_HOME: join(home, "data"),
    CODEX_HOME: join(root, "codex"),
    CLAUDE_CONFIG_DIR: join(root, "claude"),
    PI_CODING_AGENT_DIR: join(root, "pi-agent"),
    ACTION_HUB_CACHE: join(root, "ah", "catalog.json"),
    TMPDIR: join(root, "tmp"),
    TMP: join(root, "tmp"),
    TEMP: join(root, "tmp"),
    ACTION_HUB_CONFIG: join(root, "ah", "servers.json"),
    ACTION_HUB_SKILLS_DIR: join(root, "skills"),
    ACTION_HUB_DAEMON_DIR: join(root, "daemon"),
    ACTION_HUB_CREDENTIALS: join(root, "ah", "credentials.json"),
  };
  dirs["ACTION_HUB_CONTROL"] = join(root, "ah", "control.json");
  // The real owner home is determined independently of $HOME (checklist rule).
  // Refuse only paths inside the owner's app-state/harness dirs (not whole-home:
  // os.tmpdir() is under USERPROFILE on Windows). Separator-safe containment
  // via path.relative.
  const ownerHome = userInfo().homedir || homedir();
  // Full ISOLATION.md denylist. Checked unconditionally (pure path math), so a
  // var colliding even with a not-yet-existing owner dir is caught.
  const guardedDirs = [
    join(ownerHome, ".pi"),
    join(ownerHome, ".codex"),
    join(ownerHome, ".claude"),
    join(ownerHome, ".claude.json"),
    join(ownerHome, ".action-hub"),
    join(ownerHome, ".config", "action-hub"),
    join(ownerHome, ".cache", "action-hub"),
    join(ownerHome, ".config", "opencode"),
    join(ownerHome, ".local", "share", "opencode"),
    join(ownerHome, ".cursor"),
    join(ownerHome, ".copilot"),
    join(ownerHome, "Library", "Application Support", "Claude"),
    join(ownerHome, "Library", "Application Support", "Code"),
    join(ownerHome, "Library", "Application Support", "action-hub"),
    join(ownerHome, "Library", "Caches", "action-hub"),
    join(ownerHome, "Library", "Preferences", "action-hub"),
    join(ownerHome, "AppData", "Roaming", "action-hub"),
    join(ownerHome, "AppData", "Local", "action-hub"),
  ];
  // Real-home wildcard siblings: .claude*, .codex*, .cursor*, .copilot* and
  // friends are enumerated from the real home so a run root accidentally
  // derived from an inherited var pointing INSIDE such a dir is refused
  // before any write (S6-R3 #5). readdir failures are surfaced, not swallowed.
  let homeEntries;
  try {
    homeEntries = readdirSync(ownerHome);
  } catch (cause) {
    throw new Error(`isolation check aborted: cannot enumerate real home ${ownerHome}: ${cause?.message}`);
  }
  for (const entry of homeEntries) {
    if (/^\.(pi|codex|claude|cursor|copilot|action-hub|opencode)/.test(entry)) {
      guardedDirs.push(join(ownerHome, entry));
    }
  }
  const contains = (parent, child) => {
    const rel = relative(parent, resolve(child));
    return rel === "" || (!rel.startsWith("..") && !isAbsolute(rel));
  };
  // Validate the proposed root FIRST — before any mkdir/write happens.
  if (guardedDirs.some((g) => contains(g, root))) {
    throw new Error(`isolation check failed: proposed run root ${root} lies inside real harness state`);
  }
  for (const [name, value] of Object.entries(dirs)) {
    for (const guarded of guardedDirs) {
      if (contains(guarded, String(value))) {
        throw new Error(`isolation check failed: ${name}=${value} resolves inside real harness state ${guarded}`);
      }
    }
  }
  const mkdirs = [
    root, home, dirs["TMPDIR"], dirs["APPDATA"], dirs["LOCALAPPDATA"], dirs["XDG_CACHE_HOME"], dirs["XDG_CONFIG_HOME"],
    dirs["XDG_STATE_HOME"], dirs["XDG_DATA_HOME"], dirs["CODEX_HOME"], dirs["CLAUDE_CONFIG_DIR"],
    dirs["PI_CODING_AGENT_DIR"], dirname(dirs["ACTION_HUB_CONFIG"]), dirs["ACTION_HUB_DAEMON_DIR"],
    dirname(dirs["ACTION_HUB_CREDENTIALS"]),
  ];
  for (const dir of mkdirs) mkdirSync(dir, { recursive: true });
  // REPLACE inherited values — never forward caller values for these.
  const env = { ...process.env, ...dirs, NO_COLOR: "1" };
  return { root, home, env, dirs };
}

