async function piSetup(env, root) {
  // Copy provider config the way builder-3 did for PR 44: from one rig seat's
  // agent dir (user login state; copied ONLY into the temp dir, never the repo).
  const seat = process.env["STRESS_PI_SEAT"]
    ? join(process.env["STRESS_PI_SEAT"], "agent")
    : join(homedir(), ".openrig", "state", "pi", "build-builder-10@action-hub", "agent");
  const agentDir = env["PI_CODING_AGENT_DIR"];
  for (const file of ["cliproxyapi.json", "cliproxyapi-models.json", "models-store.json", "auth.json"]) {
    const src = join(seat, file);
    if (existsSync(src)) cpSync(src, join(agentDir, file));
    else writeFileSync(join(agentDir, file), "{}\n", "utf8");
  }
  if (existsSync(join(seat, "settings.json"))) {
    cpSync(join(seat, "settings.json"), join(agentDir, "settings.json"));
  } else {
    writeFileSync(join(agentDir, "settings.json"), JSON.stringify({ packages: ["npm:@router-for-me/pi-cliproxyapi-provider@1.4.20"] }, null, 2), "utf8");
  }
  if (existsSync(join(seat, "npm"))) {
    cpSync(join(seat, "npm"), join(agentDir, "npm"), { recursive: true });
  }

  const adapterInNpm = existsSync(join(agentDir, "npm", "node_modules", "pi-mcp-adapter"));
  if (!adapterInNpm) {
    // Cache-aware npm install of the adapter (same as `pi install npm:pi-mcp-adapter`).
    const npmPkgPath = join(agentDir, "npm", "package.json");
    if (existsSync(npmPkgPath)) {
      const npmPkg = JSON.parse(readFileSync(npmPkgPath, "utf8"));
      npmPkg["dependencies"] ??= {};
      npmPkg["dependencies"]["pi-mcp-adapter"] = "^2.15.0";
      writeFileSync(npmPkgPath, JSON.stringify(npmPkg, null, 2), "utf8");
    }
    const install = await runAsync("npm", ["install", "--prefix", join(agentDir, "npm"), "--prefer-offline", "--no-audit", "--no-fund", "pi-mcp-adapter@^2.15.0"], env, { timeout: 180000 });
    if (!existsSync(join(agentDir, "npm", "node_modules", "pi-mcp-adapter"))) {
      return { ok: false, note: `pi-mcp-adapter unavailable (npm install failed: ${(install.stderr || install.stdout || "").slice(-200)})` };
    }
    // Register the adapter in settings.json packages (what `pi install` does).
    const settingsPath = join(agentDir, "settings.json");
    const settings = JSON.parse(readFileSync(settingsPath, "utf8"));
    settings["packages"] ??= [];
    if (!settings["packages"].some((p) => String(p).includes("pi-mcp-adapter"))) {
      settings["packages"].push("npm:pi-mcp-adapter@2.15.0");
    }
    writeFileSync(settingsPath, JSON.stringify(settings, null, 2), "utf8");
  }
  return { ok: true };
}

