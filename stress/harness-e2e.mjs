    // modified in place; bogus entries like make-config's tools-queries.json
    // artifact are filtered in the temp copy).
    // Builders' scripts and the TypeScript build must never run with real
    // process.env: the isolated env exists before anything is spawned.
    const cli = await cliEntryPath(env);
    // Skills must live INSIDE the run root (S6-R2): copy the generated corpus.
    const tempSkillsDir = join(root, "skills");
    cpSync(join(GEN, "skills"), tempSkillsDir, { recursive: true });
    env["ACTION_HUB_SKILLS_DIR"] = tempSkillsDir;
    env["ACTION_HUB_CONFIG"] = buildTempServersConfig(env, needleManifestPath);
    env["ACTION_HUB_CLI_ENTRY"] = cli;
    // FINAL containment revalidation: every path-valued var in the FINAL env
    // (after reassignment) must lie under the temp root, separator-safe.
    const contained = (parent, child) => {
      const rel = relative(parent, resolve(child));
      return rel !== "" && !rel.startsWith("..") && !isAbsolute(rel);
    };
    const PATH_VARS = [
      "HOME", "USERPROFILE", "APPDATA", "LOCALAPPDATA", "TMPDIR",
      "XDG_CACHE_HOME", "XDG_CONFIG_HOME", "XDG_STATE_HOME", "XDG_DATA_HOME",
      "PI_CODING_AGENT_DIR", "CODEX_HOME", "CLAUDE_CONFIG_DIR",
      "ACTION_HUB_CONFIG", "ACTION_HUB_CACHE", "ACTION_HUB_SKILLS_DIR",
      "ACTION_HUB_DAEMON_DIR", "ACTION_HUB_CREDENTIALS", "ACTION_HUB_CONTROL",
    ];
    for (const k of PATH_VARS) {
      const v = env[k];
      if (typeof v === "string" && v && !contained(root, v)) {
        summary.errors.push(`containment: ${k}=${v} is not under ${root}`);
      }
    }
